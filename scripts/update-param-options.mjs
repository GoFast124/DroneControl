// Regenerates src/renderer/src/paramOptions.ts, the named choices shown in the Parameters page dropdowns, from
// ArduPilot's published ArduCopter parameter metadata.
//
//   node scripts/update-param-options.mjs [path-or-url-to-apm.pdef.json]
//
// Only parameters that list a fixed set of numeric choices are included. Numeric ranges and bitmasks are left alone.
import fs from 'node:fs'

const SOURCE = process.argv[2] ?? 'https://autotest.ardupilot.org/Parameters/ArduCopter/apm.pdef.json'
const OUT = new URL('../src/renderer/src/paramOptions.ts', import.meta.url)

const text = /^https?:/.test(SOURCE) ? await (await fetch(SOURCE)).text() : fs.readFileSync(SOURCE, 'utf8')
const groups = JSON.parse(text)

const lists = []
const listIndex = new Map()
const byParam = {}
for (const group of Object.values(groups)) {
  for (const [name, meta] of Object.entries(group)) {
    if (!meta.Values) continue
    const entries = Object.entries(meta.Values).map(([value, label]) => [Number(value), String(label)])
    if (entries.length < 2 || entries.some(([value]) => Number.isNaN(value))) continue
    // A parameter with a wide numeric range that only lists a few example values (ATC_ACC_P_MAX, ATC_INPUT_TC, MOT_SPIN_MIN...)
    // is a number with presets, not a choice, so it stays a plain number. Baud codes are the exception: they are real choices.
    if (meta.Range) {
      const span = Number(meta.Range.high) - Number(meta.Range.low)
      const preset = entries.some(([value]) => !Number.isInteger(value)) || (span > 50 && entries.length < span / 4)
      if (preset && !/_(BAUD|BD)$/.test(name)) continue
    }
    entries.sort((a, b) => a[0] - b[0])
    const key = JSON.stringify(entries)
    if (!listIndex.has(key)) {
      listIndex.set(key, lists.length)
      lists.push(entries)
    }
    byParam[name] = listIndex.get(key)
  }
}

const names = Object.keys(byParam).sort()
const body = `// Generated by scripts/update-param-options.mjs from ${SOURCE}. Do not edit by hand.
// Newer firmware can have choices an older vehicle doesn't know, so a value is only a suggestion until the vehicle confirms it.

export type ParamChoice = [value: number, label: string]

const LISTS: ParamChoice[][] = ${JSON.stringify(lists)}

const BY_PARAM: Record<string, number> = ${JSON.stringify(Object.fromEntries(names.map((n) => [n, byParam[n]])))}

// The named choices for a parameter, or undefined if it is a plain number.
export function paramChoices(id: string): ParamChoice[] | undefined {
  const index = BY_PARAM[id]
  return index === undefined ? undefined : LISTS[index]
}
`
fs.writeFileSync(OUT, body)
console.log(`${names.length} parameters with choices, ${lists.length} distinct lists, ${(body.length / 1024).toFixed(0)} KB`)
